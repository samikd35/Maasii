// Writes .env.local for this worktree from its running local Supabase stack.
// Ports differ per worktree and change after `supabase stack destroy`, so never hard-code them.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let status;
try {
  status = JSON.parse(
    execFileSync("pnpm", ["-s", "supabase", "status", "--output-format", "json"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
} catch {
  console.error("Could not read the local Supabase stack. Start it with `pnpm db:start`.");
  process.exit(1);
}

const env = status.env ?? {};
for (const key of ["API_URL", "DB_URL", "PUBLISHABLE_KEY", "SECRET_KEY"]) {
  if (!env[key]) {
    console.error(`Supabase status has no ${key}. Is the stack running? Try \`pnpm db:start\`.`);
    process.exit(1);
  }
}

const lines = [
  "# Generated by `pnpm db:env` from this worktree's local Supabase stack. Do not edit or commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${env.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${env.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${env.SECRET_KEY}`,
  `DATABASE_URL=${env.DB_URL}`,
  "",
];
writeFileSync(new URL("../.env.local", import.meta.url), lines.join("\n"));
console.log(`Wrote .env.local (API ${env.API_URL}, DB ${env.DB_URL.replace(/:[^:@/]+@/, ":***@")})`);
